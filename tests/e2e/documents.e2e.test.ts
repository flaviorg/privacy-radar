test("[RF-5] a pt-BR run after an en run into the same --out leaves no registro.md or ripd.md", async (t) => {
  const out = tmpDir(t);
  await docsRun(t, { out, reportLang: "en" });
  assert.ok(existsSync(join(out, "registro.md")) && existsSync(join(out, "ripd.md")));
  await docsRun(t, { out, reportLang: "pt-BR" });
  assert.ok(!existsSync(join(out, "registro.md")) && !existsSync(join(out, "ripd.md")) && existsSync(join(out, "registro.pt-BR.md")));
  await docsRun(t, { out, docs: [] });
  assert.ok(!["ropa.md", "dpia.md", "registro.pt-BR.md", "ripd.pt-BR.md"].some((f) => existsSync(join(out, f))), "--docs none removes the documents of the previous run");
});

test("[RF-5] the scan never deletes a file it does not own", async (t) => {
  const out = tmpDir(t);
  writeFileSync(join(out, "notes.txt"), "keep me\n");
  writeFileSync(join(out, "ropa.backup.md"), "keep me too\n");
  await docsRun(t, { out, reportLang: "en" });
  await docsRun(t, { out, docs: [] });
  assert.equal(readFileSync(join(out, "notes.txt"), "utf8"), "keep me\n");
  assert.equal(readFileSync(join(out, "ropa.backup.md"), "utf8"), "keep me too\n");
});
