/** The order documents are written and listed in. */
export const DOC_ORDER: readonly DocId[] = ["ropa", "dpia", "registro", "ripd"];

/** `ropa.md`, `dpia.md`; `registro.md`/`ripd.md` in English, `registro.pt-BR.md`/`ripd.pt-BR.md` in pt-BR (DOC-08). */
export function documentFileName(doc: DocId, locale: Locale): string {
  if (doc === "ropa" || doc === "dpia" || locale === "en") return `${doc}.md`;
  return `${doc}.${locale}.md`;
}

/** The locale a document is rendered in: the GDPR documents are always English. */
export function documentLocale(doc: DocId, reportLang: Locale): Locale {
  return DOCUMENTS[doc].locales.includes(reportLang) ? reportLang : "en";
}

