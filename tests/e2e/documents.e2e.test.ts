const read = (dir: string, name: string) => readFileSync(join(dir, name), "utf8");
const NARRATIVE_HEADING = /^### (?:Draft narrative \(LLM\)|Rascunho narrativo \(LLM\))$/;
const PLACEHOLDER = /^_(?:Narrative unavailable \(LLM output rejected: [^)]+\)|Narrativa indisponível \(saída do LLM rejeitada: [^)]+\))\._$/;
const NOT_GENERATED = /^_(?:Narrative not generated: the scan ran without a language model|Narrativa não gerada: a varredura rodou sem modelo de linguagem)\._$/;

/** The narrative blocks of a document: the lines after each narrative heading up to the next heading or table. */
function narrativeBlocks(md: string): string[][] {
  const lines = md.split("\n");
  const blocks: string[][] = [];
  for (let i = 0; i < lines.length; i++) {
    if (!NARRATIVE_HEADING.test(lines[i]!)) continue;
    const body: string[] = [];
    for (let j = i + 1; j < lines.length && !lines[j]!.startsWith("#") && !lines[j]!.startsWith("|") && !lines[j]!.startsWith("_None") && !lines[j]!.startsWith("_Nenhum"); j++) {
      if (lines[j] !== "") body.push(lines[j]!);
    }
    blocks.push(body);
  }
  return blocks;
}

test("[DOC-08] --report-lang pt-BR writes registro.pt-BR.md and ripd.pt-BR.md instead of registro.md and ripd.md, and ropa.md and dpia.md in English", () => {
  assert.deepEqual(readdirSync(pt.outDir).filter((f) => f.endsWith(".md")).sort(), ["dpia.md", "inventory.md", "registro.pt-BR.md", "ripd.pt-BR.md", "ropa.md"]);
  assert.deepEqual(readdirSync(en.outDir).filter((f) => f.endsWith(".md")).sort(), ["dpia.md", "inventory.md", "registro.md", "ripd.md", "ropa.md"]);
  assert.match(read(pt.outDir, "ropa.md"), /^> \*\*Draft generated by privacy-radar/);
  assert.match(read(pt.outDir, "registro.pt-BR.md"), /^> \*\*Rascunho gerado por privacy-radar/);
  assert.match(read(en.outDir, "registro.md"), /^> \*\*Draft generated by privacy-radar/);
  assert.deepEqual(pt.documents.map((d) => d.name), ["ropa.md", "dpia.md", "registro.pt-BR.md", "ripd.pt-BR.md"]);
});

test("[DOC-01] every document starts with the banner and keeps the sections in order", () => {
  const files: [keyof typeof DOCUMENTS, string][] = [["ropa", "ropa.md"], ["dpia", "dpia.md"], ["registro", "registro.pt-BR.md"], ["ripd", "ripd.pt-BR.md"]];
  for (const [doc, name] of files) {
    const md = read(pt.outDir, name);
    assert.match(md, /^> \*\*(?:Draft generated by|Rascunho gerado por) privacy-radar/);
    assert.match(md.split("\n")[0]!, /privacy-radar 0\.1\.0 (?:on|em) 2026-10-08 (?:from|a partir de) fixtures\/telehealth-clinic\..*(?:Provider|Provedor): fake \(scripted\)\.\*\*$/);
    assert.equal(md.match(/^## /gm)?.length, DOCUMENTS[doc].sections.length, name);
    assert.doesNotMatch(md, /\{\{/, `${name}: no unfilled placeholder`);
    assert.doesNotMatch(md, /\n\n\n/, `${name}: no triple newline`);
    assert.match(md.trimEnd(), /(?:This is not legal advice and not a complete assessment\.|Isto não é aconselhamento jurídico nem uma avaliação completa\.)$/);
  }
});

test("[DOC-05] narratives sit only under Draft narrative (LLM) or Rascunho narrativo (LLM) headings", () => {
  const names = ["ropa.md", "dpia.md", "registro.pt-BR.md", "ripd.pt-BR.md"];
  const blocks = names.flatMap((n) => narrativeBlocks(read(pt.outDir, n)));
  assert.equal(blocks.length, 8);
  for (const b of blocks) {
    assert.ok(b.length >= 1, "a block has at least one paragraph");
    for (const p of b) assert.doesNotMatch(p, PLACEHOLDER, "the demo fixture's narratives are accepted");
  }
  assert.equal(narrativeBlocks(read(pt.outDir, "registro.pt-BR.md"))[0]!.join(" ").length > 20, true);
  assert.match(read(pt.outDir, "registro.pt-BR.md"), /^### Rascunho narrativo \(LLM\)$/m);
  assert.equal(pt.result.llm.narrativeSections, 8);
  assert.equal(pt.result.llm.calls, 10);
  assert.equal(pt.result.llm.repaired, 1, "dpia.description carries the simulated invalid-json then ok turn");
  assert.equal(pt.result.llm.simulated, true);
  const narrativeTrace = pt.trace.filter((l) => l.prompt === "draft-narrative.v1");
  assert.equal(narrativeTrace.length, 8);
  assert.deepEqual(narrativeTrace.map((l) => l.matchKeys), [
    { document: "ropa", section: "purposes" },
    { document: "ropa", section: "security-measures" },
    { document: "dpia", section: "description" },
    { document: "dpia", section: "necessity-proportionality" },
    { document: "dpia", section: "measures" },
    { document: "registro", section: "finalidades" },
    { document: "registro", section: "seguranca" },
    { document: "ripd", section: "medidas-salvaguardas" },
  ]);
  assert.equal(narrativeTrace.find((l) => l.matchKeys.section === "description")!.outcome, "repaired");
  assert.equal(narrativeTrace.find((l) => l.matchKeys.section === "description")!.simulated, true);
  assert.ok(existsSync(join(pt.outDir, "llm-trace.jsonl")));
});

test("[DOC-05] numbers-drift and article-drift fixtures render the rejection line and the trace records the reason", async (t) => {
  for (const [fixture, reasons] of [
    ["tests/fixtures/llm/numbers-drift.json", ["numbers-drift"]],
    ["tests/fixtures/llm/article-drift.json", ["article-drift", "numbers-drift"]],
  ] as const) {
    const run = await docsRun(t, { reportLang: "en", llm: fake(fixture) });
    const blocks = run.documents.flatMap((d) => narrativeBlocks(d.content));
    assert.equal(blocks.length, 8, fixture);
    for (const b of blocks) {
      assert.equal(b.length, 1, fixture);
      assert.match(b[0]!, PLACEHOLDER, fixture);
    }
    const outcomes = run.trace.filter((l) => l.prompt === "draft-narrative.v1").map((l) => l.outcome);
    assert.equal(outcomes.length, 8);
    for (const o of outcomes) assert.ok((reasons as readonly string[]).includes(o), `${fixture}: ${o}`);
    assert.equal(run.result.llm.narrativeSections, 0);
    if (fixture.includes("article-drift")) {
      assert.deepEqual(outcomes.slice(0, 7), Array(7).fill("article-drift"), "every citation form is rejected as article drift");
      assert.equal(outcomes[7], "numbers-drift", "the spelled-out number");
    }
    assert.match(run.documents.find((d) => d.name === "dpia.md")!.content, /_Narrative unavailable \(LLM output rejected: (?:numbers|article)-drift\)\._/);
  }
});

test("[DOC-06] with --llm none every narrative section says no model ran and every table equals the --llm fake run", () => {
  for (const name of ["ropa.md", "dpia.md", "registro.pt-BR.md", "ripd.pt-BR.md"]) {
    const fakeMd = read(pt.outDir, name);
    const noneMd = read(none.outDir, name);
    const blocks = narrativeBlocks(noneMd);
    assert.ok(blocks.length >= 1);
    for (const b of blocks) {
      assert.equal(b.length, 1);
      assert.match(b[0]!, NOT_GENERATED);
    }
    // the advisory sub-table is the one place an LLM label appears (DOC-09); everything else must match
    const withoutAdvisory = (md: string) => md.replace(/^### (?:LLM-labeled fields \(advisory\)|Campos rotulados pelo LLM \(consultivo\))\n[\s\S]*?(?=^##)/m, "");
    const tablesOf = (md: string) => withoutAdvisory(md).split("\n").filter((l) => l.startsWith("|") || l.startsWith("- ") || /^\d+ (?:of|indicadores|high-risk)/.test(l));
    assert.deepEqual(tablesOf(noneMd), tablesOf(fakeMd), name);
  }
  assert.equal(none.result.llm.calls, 0);
  assert.equal(none.result.llm.narrativeSections, 0);
});

test("evidence-index rows resolve to findings in findings.json", () => {
  const json = JSON.parse(read(pt.outDir, "findings.json")) as { findings: { id: string; ruleId: string; location: { file: string; line: number } }[] };
  const byId = new Map(json.findings.map((f) => [f.id, f]));
  for (const name of ["ropa.md", "dpia.md", "registro.pt-BR.md", "ripd.pt-BR.md"]) {
    const md = read(pt.outDir, name);
    const evidence = md.slice(md.lastIndexOf("\n## ")).split("\n").filter((l) => l.startsWith("- PRF-"));
    assert.equal(evidence.length, 17, name);
    for (const row of evidence) {
      const m = /^- (PRF-[0-9a-f]{12}) · (PR-[A-Z-]+) · `([^`]+):(\d+)`$/.exec(row);
      assert.ok(m, row);
      const f = byId.get(m[1]!);
      assert.ok(f, row);
      assert.deepEqual([f.ruleId, f.location.file, f.location.line], [m[2], m[3], Number(m[4])]);
    }
  }
});

